#include <bits/stdc++.h>
using namespace std;
 
int main(){
    long long n, m;
    cin>>n;
    cin>>m;
    
    cout<<n<<" + "<<m<<" = "<<n + m<<endl<<endl;
    cout<<n<<" - "<<m<<" = "<<n - m<<endl<<endl;
    cout<<n<<" * "<<m<<" = "<<n * m<<endl<<endl;
    cout<<n<<" / "<<m<<" = "<<n / m<<endl<<endl;
    cout<<n<<" % "<<m<<" = "<<n % m<<endl;
    
    return 0;
}